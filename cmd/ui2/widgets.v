module main

import os

// A module's widget registry for the VML interpreter. `// vml: widgets` in one
// of its files makes `ui2 gen` write `vml_widgets_d_vml_interpreter.v` beside
// it: every public `XProps` type of the module with a `build` or `part`
// method is the tag `X`. In ui2 these are the builtin tags; another module's
// widgets register as `module.X` when the program starts, the tag compiled
// VML resolves to `module.XProps`.

const widgets_file = 'vml_widgets_d_vml_interpreter.v'

// widget_registry is the registry file of the module `module` in `dir`.
fn widget_registry(dir string, module string) !string {
	types := widget_props(dir)!
	if types.len == 0 {
		return error('${dir}: `// vml: widgets` finds no public props type with a `build` or `part` method')
	}
	mut width := 0
	for typ in types {
		width = if typ.len - 5 > width { typ.len - 5 } else { width }
	}
	mut out := []string{}
	out << '// Generated by `ui2 gen` (`// vml: widgets`) from the props types of this'
	out << '// module: each public `XProps` type with a `build` or `part` method is the'
	out << '// VML tag `X`. Do not edit; add or remove a props type and regenerate.'
	out << 'module ${module}'
	out << ''
	if module == 'ui2' {
		out << '// The builtin tags of the VML interpreter.'
		out << 'const vml_builtin_widgets = {'
		for typ in types {
			tag := typ.all_before_last('Props')
			out << "\t'${tag}':${' '.repeat(width - tag.len + 1)}vml_widget[${typ}]()"
		}
		out << '}'
	} else {
		out << 'import ui2'
		out << ''
		out << 'fn init() {'
		for typ in types {
			tag := '${module}.${typ.all_before_last('Props')}'
			out << "\tui2.vml_register('${tag}', ui2.vml_widget[${typ}]()) or { panic(err) }"
		}
		out << '}'
	}
	return out.join('\n') + '\n'
}

// widget_props lists, sorted by tag, the public props types declared in the
// module's files with a `build` or `part` method. Tests, generated builders
// and files compiled only under a flag are not read.
fn widget_props(dir string) ![]string {
	mut declared := []string{}
	mut built := map[string]bool{}
	for entry in os.ls(dir)! {
		if !entry.ends_with('.v') || entry.ends_with('_test.v') || entry.contains('_d_')
			|| is_generated(entry) {
			continue
		}
		for raw in os.read_lines(os.join_path(dir, entry))! {
			line := raw.trim_space()
			if line.starts_with('pub struct ') {
				name := line.all_after('pub struct ').all_before('{').all_before('[').trim_space()
				if name.len > 5 && name.ends_with('Props') && name !in declared {
					declared << name
				}
			} else if line.starts_with('pub fn (') {
				receiver := line.all_after('pub fn (').all_before(')')
				method := line.all_after(') ').all_before('(').trim_space()
				if method in ['build', 'part'] {
					built[receiver.all_after_last(' ').trim_left('&')] = true
				}
			}
		}
	}
	mut types := declared.filter(it in built)
	types.sort(a.all_before_last('Props') < b.all_before_last('Props'))
	return types
}
